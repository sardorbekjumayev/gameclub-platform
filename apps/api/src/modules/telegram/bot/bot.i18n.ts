export function bt(lang: BotLang, key: BotKey | string, vars: Record<string, string | number> = {}): string {
  const s = (DICT[lang] as Record<string, string>)[key] ?? (uz as Record<string, string>)[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Reply-keyboard tugmasi matni → bo'lim (barcha tillarda, foydalanuvchi tilni o'zgartirgan bo'lsa ham ishlaydi). */
export const MENU_SECTIONS = ['tickets', 'history', 'profile', 'notifications', 'settings', 'help'] as const;
export type MenuSection = (typeof MENU_SECTIONS)[number];

export function menuSection(text: string): MenuSection | null {
  for (const s of MENU_SECTIONS) for (const l of Object.keys(DICT) as BotLang[]) if (DICT[l][`menu.${s}`] === text) return s;
  return null;
}
